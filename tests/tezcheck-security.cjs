const assert = require('node:assert/strict');
const {createHmac} = require('node:crypto');
const fs = require('node:fs');
const Module = require('node:module');
const path = require('node:path');
const ts = require('typescript');
const filename = path.resolve('src/lib/payments/tezcheck-security.ts');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const mod = new Module(filename, module);
mod.filename=filename;mod.paths=Module._nodeModulePaths(path.dirname(filename));mod._compile(compiled,filename);
const {validWebhook,verifiedPayment} = mod.exports;
const now=Date.now(), timestamp=String(Math.floor(now/1000)), secret='isolated-test-secret';
const raw=JSON.stringify({id:'event-1',data:{environment:'live'}});
const sign=(body=raw,time=timestamp,delivery='delivery-1')=>'v1='+createHmac('sha256',secret).update(`${time}.${delivery}.${body}`).digest('hex');
const headers=new Headers({'x-checkout-timestamp':timestamp,'x-checkout-delivery':'delivery-1','x-checkout-signature':sign()});
assert.equal(validWebhook(raw,headers,secret,now),true);
assert.equal(validWebhook(raw+' ',headers,secret,now),false);
assert.equal(validWebhook(raw,headers,'wrong-key',now),false);
assert.equal(validWebhook(raw,headers,secret,now+301000),false);
headers.set('x-checkout-signature','v2='+sign().slice(3));
assert.equal(validWebhook(raw,headers,secret,now),false);
headers.set('x-checkout-signature','v1='+'0'.repeat(64)+','+sign());
assert.equal(validWebhook(raw,headers,secret,now),true);
const order={id:'order-1',billId:'bill-1',amount:299000};
const good={bill:{id:'bill-1',external_reference:'order-1',amount_minor:29900000,currency:'UZS',paid:true,livemode:true,environment:'live'},payment:{id:'pay-1',state:'succeeded',amount_minor:29900000,currency:'UZS',livemode:true,environment:'live',refunded_amount_minor:0}};
assert.equal(verifiedPayment(good,order),'pay-1');
const changed=(part,patch)=>({...good,[part]:{...good[part],...patch}});
assert.equal(verifiedPayment(changed('bill',{paid:false}),order),null);
assert.equal(verifiedPayment(changed('bill',{environment:'test',livemode:false}),order),null);
assert.equal(verifiedPayment(changed('payment',{environment:'test',livemode:false}),order),null);
assert.equal(verifiedPayment(changed('payment',{state:'processing'}),order),null);
assert.equal(verifiedPayment(changed('payment',{refunded_amount_minor:100}),order),null);
assert.throws(()=>verifiedPayment(changed('bill',{external_reference:'foreign-order'}),order));
assert.throws(()=>verifiedPayment(changed('bill',{id:'foreign-bill'}),order));
assert.throws(()=>verifiedPayment(changed('payment',{amount_minor:100}),order));
assert.throws(()=>verifiedPayment(changed('bill',{currency:'USD'}),order));
