    assert.equal((await prisma.user.findUnique({ where: { id: cashier.id } })).status, 'INACTIVE');
    const seed = require('node:child_process').spawnSync(process.execPath, ['scripts/seed.mjs'], { env: { ...process.env, NODE_ENV: 'production' }, encoding: 'utf8' });
    assert.equal(seed.status, 1);
    assert.equal(await prisma.shop.count({ where: { id: { in: shops.map(row => row.id) } } }), 2);
